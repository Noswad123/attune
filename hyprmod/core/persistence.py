MARKER = "-- Generated by Attune\n"
RECORD = "-- Attune data v1: "
SECTION_KEYS = {"monitors": "monitor", "animations": "animation", "beziers": "bezier"}
OPTION_KEY = re.compile(r"(?:decoration|animations):[A-Za-z_][A-Za-z0-9_.:]*")


def _document(values: dict, sections: dict) -> Document:
    doc = Document(lines=[Comment(raw="# Generated by Attune\n", text="Generated by Attune")])
    for key, value in sorted(values.items()):
        if not isinstance(key, str) or not (key in GENERAL_OPTIONS or OPTION_KEY.fullmatch(key)):
            raise ValueError(f"Unsupported Attune option: {key}")
        if not isinstance(value, str) or any(ord(c) < 32 for c in value) or "$" in value:
            raise ValueError(f"Unsupported scalar value for {key}")
        if re.fullmatch(r"[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?", value.strip()):
            if not math.isfinite(float(value)):
                raise ValueError(f"Non-finite numeric value for {key}")
        doc.lines.append(Assignment(raw=f"{key} = {value}\n", key=key, full_key=key, value=value))
    for section, lines in sections.items():
        if section not in SECTION_KEYS:
            if lines is not None:
                raise ValueError(f"Unsupported Attune section: {section}")
    for section in ("beziers", "animations", "monitors"):
        lines = sections.get(section)
        if lines is None:
            continue
        if not isinstance(lines, list):
            raise ValueError(f"Invalid section: {section}")
        keyword = SECTION_KEYS[section]
        for line in lines:
            if not isinstance(line, str):
                raise ValueError(f"Invalid {section} line")
            line = line.rstrip("\n")
            if any(ord(c) < 32 for c in line) or "$" in line:
                raise ValueError(f"Invalid {section} line")
            match = re.fullmatch(rf"{keyword}\s*=\s*(.*)", line)
            if match is None:
                raise ValueError(f"Unsupported {section} directive")
            value = match[1]
            parts = [part.strip() for part in value.split(",")]
            if keyword == "bezier" and (
                len(parts) != 5
                or not all(re.fullmatch(r"-?(?:\d+(?:\.\d*)?|\.\d+)", p) for p in parts[1:])
            ):
                raise ValueError("Invalid bezier definition")
            if keyword == "animation":
                if len(parts) not in (2, 4, 5) or not all(parts):
                    raise ValueError("Invalid animation definition")
                enabled = parse_hyprlang_bool(parts[1])
                if enabled is None or (len(parts) == 2 and enabled):
                    raise ValueError("Invalid animation enabled flag or missing animation fields")
            if keyword == "monitor" and not (
                (len(parts) == 2 and parts[1] == "disable")
                or (len(parts) >= 4 and len(parts) % 2 == 0)
            ):
                raise ValueError("Invalid monitor definition")
            doc.lines.append(Keyword(raw=line + "\n", key=keyword, value=value))
    return doc


def _render(values: dict, sections: dict) -> str:
    doc = _document(values, sections)
    record = base64.b64encode(
        json.dumps([values, sections], sort_keys=True, ensure_ascii=True).encode("ascii")
    ).decode("ascii")
    lua = serialize_lua(doc)
    if not lua.startswith(MARKER):
        raise ValueError("Lua emitter did not preserve Attune ownership")
    return MARKER + RECORD + record + "\n" + lua[len(MARKER) :]


def build_text(values: dict[str, str], sections: "ConfigSections") -> str:
    return _render(values, asdict(sections))


def read_document(text: str) -> Document:
    """Reparse data, then require byte-exact canonical output, not arbitrary Lua."""
    if not text:
        return Document()
    if not text.startswith(MARKER + RECORD):
        raise ValueError("Refusing foreign file: expected Generated by Attune ownership and data")
    try:
        record = text.split("\n", 2)[1][len(RECORD) :]
        try:
            data = json.loads(base64.b64decode(record, validate=True))
        except RecursionError as exc:
            raise ValueError("Attune data record is too deeply nested") from exc
        values, sections = data
        if not isinstance(values, dict) or not isinstance(sections, dict):
            raise ValueError("Invalid Attune data")
        doc = _document(values, sections)
        if _render(values, sections) != text:
            raise ValueError("Attune file was edited outside Attune; refusing to overwrite")
        return doc
    except (binascii.Error, UnicodeError, TypeError, IndexError) as exc:
        raise ValueError("Invalid Attune data record") from exc


def validate_lua(text: str) -> None:
    luac = shutil.which("luac")
    lua = shutil.which("lua") if luac is None else None
    if luac is None and lua is None:
        raise ValueError("Install lua or luac to compile-check Attune output; nothing was saved")
    command = (
        [luac, "-p", "-"]
        if luac is not None
        else [
            str(lua),
            "-E",
            "-e",
            'local s=io.read("*a"); local f,e=load(s,"attune","t"); '
            "if not f then io.stderr:write(e); os.exit(1) end",
        ]
    )
    try:
        result = subprocess.run(command, input=text, text=True, capture_output=True, timeout=10)
    except subprocess.TimeoutExpired as exc:
        raise ValueError("Lua syntax validation timed out; nothing was saved") from exc
    if result.returncode:
        raise ValueError(f"Lua syntax validation failed: {result.stderr.strip()}")


def resolve_target(path: Path) -> Path:
    """Resolve a dedicated Attune destination without replacing its symlinks."""
    if path.name != "attune.lua":
        raise ValueError("Attune can only save its dedicated attune.lua file")
    # strict resolution rejects dangling links, including links in parent directories.
    try:
        target = path.resolve(strict=True)
    except RuntimeError as exc:
        raise ValueError("Cyclic configuration symlink") from exc
    except FileNotFoundError:
        if path.is_symlink():
            raise ValueError("Dangling attune.lua symlink; provision its target first") from None
        target = path.parent.resolve(strict=True) / path.name
    if target.name != "attune.lua":
        raise ValueError("Resolved target must also be named attune.lua, never a main config")
    if target.exists():
        info = target.stat()
        if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
            raise ValueError("Attune refuses non-regular files and hardlinked targets")
    config_home = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config"))
    for main in (config_home / "hypr" / "hyprland.lua", config_home / "hypr" / "hyprland.conf"):
        if main.exists() and target.exists() and target.samefile(main):
            raise ValueError("Attune refuses aliases to the main config")
    return target


def _atomic_write(
    path: Path,
    content: bytes,
    *,
    exclusive: bool = False,
    before_replace: Callable[[], None] | None = None,
) -> None:
    fd, name = tempfile.mkstemp(prefix=".attune-", dir=path.parent)
    temporary = Path(name)
    replaced = False
    attempted = False
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        if before_replace is not None:
            before_replace()
        try:
            if exclusive:
                os.link(temporary, path, follow_symlinks=False)
            else:
                attempted = True
                os.replace(temporary, path)
            replaced = True
            directory = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
            try:
                os.fsync(directory)
            finally:
                os.close(directory)
        except OSError as exc:
            raise PersistenceFailure(str(exc), may_have_written=not exclusive) from exc
    finally:
        # Cleanup must not turn a successful replacement into an apparent failed save.
        try:
            temporary.unlink(missing_ok=True)
        except OSError as exc:
            if not replaced:
                if attempted:
                    raise PersistenceFailure(str(exc), may_have_written=True) from exc
                raise


class PersistenceFailure(OSError):
    def __init__(self, message: str, *, may_have_written: bool = False):
        super().__init__(message)
        self.may_have_written = may_have_written


@dataclass(frozen=True)
class RecoveryPreservation:
    root: Path
    path: Path


def _private_directory(path: Path, *, create: bool) -> None:
    if create:
        try:
            path.mkdir(mode=0o700)
        except FileExistsError:
            pass
    info = path.lstat()
    if (
        not stat.S_ISDIR(info.st_mode)
        or stat.S_IMODE(info.st_mode) != 0o700
        or info.st_uid != os.getuid()
    ):
        raise ValueError("Recovery requires private owned 0700 directories, not symlinks")


def recovery_root() -> Path:
    """Resolve the evidence destination without creating or chmodding user directories."""
    state = Path(os.environ.get("XDG_STATE_HOME", Path.home() / ".local/state"))
    if not state.is_absolute():
        raise ValueError("Recovery state storage must be absolute")
    root = state / "attune/preserved"
    resolved = root.resolve()
    for parent in (resolved, *resolved.parents):
        if (parent / ".git").exists():
            raise ValueError("Recovery state storage must be outside Git")
    for directory in (state / "attune", root):
        if directory.exists() or directory.is_symlink():
            _private_directory(directory, create=False)
    return resolved


def _preserve(guard: RecoveryPreservation, previous: bytes) -> None:
    if recovery_root() != guard.root or guard.path != guard.root / (
        hashlib.sha256(previous).hexdigest() + ".bin"
    ):
        raise ValueError("Preservation destination changed since review")
    _private_directory(guard.root, create=True)
    try:
        fd = os.open(guard.path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    except FileExistsError:
        pass
    else:
        with os.fdopen(fd, "wb") as stream:
            stream.write(previous)
            stream.flush()
            os.fsync(stream.fileno())
    _verify_preservation(guard, previous)
    # Existing evidence must also be durable before any configuration replacement.
    fd = os.open(guard.path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)
    # Sync the parent as well so a newly created preserved/ entry is durable.
    for path in (guard.root, guard.root.parent):
        directory = os.open(path, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)
    _verify_preservation(guard, previous)


def _verify_preservation(guard: RecoveryPreservation, previous: bytes) -> None:
    if recovery_root() != guard.root:
        raise ValueError("Preservation root changed since review")
    info = guard.path.lstat()
    if stat.S_IMODE(info.st_mode) != 0o600 or info.st_uid != os.getuid():
        raise ValueError("Preserved evidence must be private owned 0600")
    raw = read_stable(guard.path, limit=256 * 1024)
    after = guard.path.lstat()
    if any(
        getattr(info, key) != getattr(after, key)
        for key in ("st_dev", "st_ino", "st_mode", "st_uid", "st_nlink", "st_ctime_ns")
    ):
        raise ValueError("Preserved evidence permissions or identity changed during verification")
    if raw != previous or guard.path.name != hashlib.sha256(raw).hexdigest() + ".bin":
        raise ValueError("Preserved evidence differs from original bytes")


def persist_recovery(
    snapshot: ReviewSnapshot,
    *,
    preservation: RecoveryPreservation,
    expected_source: Callable[[], None],
    cancel_event: threading.Event | None = None,
) -> Path:
    """Separate preservation-gated transaction, never an ordinary-save override."""
    previous = snapshot.saved_text
    if (
        not previous
        or len(previous.encode()) > 256 * 1024
        or len(previous.splitlines()) > 10000
        or any((ord(c) < 32 and c not in "\t\r\n") or 127 <= ord(c) <= 159 for c in previous)
    ):
        raise ValueError("Recovery requires bounded nonempty UTF-8 text")
    try:
        read_document(previous)
    except (ValueError, RecursionError):
        pass
    else:
        raise ValueError("Owned output requires ordinary restoration")
    replacing = [False]
    try:
        _persist_snapshot(snapshot, expected_source, cancel_event, replacing, preservation)
    except OSError as exc:
        if replacing[0]:
            raise PersistenceFailure(str(exc), may_have_written=True) from exc
        raise
    return preservation.path


def read_stable(path: Path, *, limit: int = 1024 * 1024) -> bytes:
    def signature(info: os.stat_result) -> tuple[int, ...]:
        # Reads may legitimately update atime; only content/identity metadata is bound.
        return (
            info.st_dev,
            info.st_ino,
            info.st_mode,
            info.st_nlink,
            info.st_size,
            info.st_mtime_ns,
            info.st_ctime_ns,
        )

    before = path.lstat()
    if not stat.S_ISREG(before.st_mode) or before.st_nlink != 1:
        raise ValueError("Refusing symlink, hardlink or non-regular file")
    if before.st_size > limit:
        raise ValueError("File exceeds read limit")
    fd = os.open(path, os.O_RDONLY | os.O_NONBLOCK | os.O_NOFOLLOW)
    with os.fdopen(fd, "rb") as stream:
        opened = os.fstat(stream.fileno())
        if signature(before) != signature(opened):
            raise ValueError("File changed before read")
        raw = stream.read(limit + 1)
        after = os.fstat(stream.fileno())
    if (
        signature(opened) != signature(after)
        or signature(after) != signature(path.lstat())
        or len(raw) != after.st_size
    ):
        raise ValueError("File changed during read")
    if len(raw) > limit:
        raise ValueError("File exceeds read limit")
    return raw


def persist_reviewed(
    snapshot: ReviewSnapshot, values: dict[str, str], sections: "ConfigSections"
) -> Path | None:
    """Recheck review and ownership under an advisory lock before replacement."""
    if snapshot.resolved_path is None:
        raise ValueError("Review is not bound to a resolved destination; review again")
    target = resolve_target(snapshot.path)
    if target != snapshot.resolved_path:
        raise ValueError("Destination changed since review; review again")
    proposed = build_text(values, sections)
    if proposed != snapshot.proposed_text:
        raise ValueError("Draft changed; review the updated diff")
    return persist_snapshot(snapshot)


def persist_snapshot(
    snapshot: ReviewSnapshot,
    *,
    expected_source: Callable[[], None] | None = None,
    cancel_event: threading.Event | None = None,
) -> Path | None:
    """Protected transaction; source guard runs before, under lock and before replacement."""
    replacing = [False]
    try:
        return _persist_snapshot(snapshot, expected_source, cancel_event, replacing)
    except OSError as exc:
        if replacing[0]:
            raise PersistenceFailure(str(exc), may_have_written=True) from exc
        raise


def _persist_snapshot(
    snapshot: ReviewSnapshot,
    expected_source: Callable[[], None] | None,
    cancel_event: threading.Event | None,
    replacing: list[bool],
    preservation: RecoveryPreservation | None = None,
) -> Path | None:
    if snapshot.resolved_path is None:
        raise ValueError("Review is not bound to a resolved destination; review again")
    target = resolve_target(snapshot.path)
    if target != snapshot.resolved_path:
        raise ValueError("Destination changed since review; review again")
    proposed = snapshot.proposed_text

    def check():
        if cancel_event is not None and cancel_event.is_set():
            raise InterruptedError("Save cancelled before replacement")
        if expected_source is not None:
            expected_source()

    check()
    read_document(proposed)
    validate_lua(proposed)
    if (read_stable(target) if target.exists() else b"").decode("utf-8") != snapshot.saved_text:
        raise ValueError("Output file changed; review the updated diff")
    if proposed == snapshot.saved_text:
        if proposed:
            read_document(proposed)
        check()
        if resolve_target(snapshot.path) != target or read_stable(target).decode() != proposed:
            raise ValueError("Output file changed; review again")
        return None
    state = Path(os.environ.get("XDG_STATE_HOME", Path.home() / ".local" / "state")) / "attune"
    resolved_backups = (state / "backups").resolve()
    for parent in (state.resolve(), resolved_backups):
        for ancestor in (parent, *parent.parents):
            if (ancestor / ".git").exists():
                raise ValueError("Backup directory must be outside the dotfiles repository")
    state.mkdir(parents=True, exist_ok=True, mode=0o700)
    if preservation is not None:
        if recovery_root() != preservation.root:
            raise ValueError("Preservation root changed since review")
        _private_directory(state, create=False)
    lock_fd = os.open(state / "persistence.lock", os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600)
    with os.fdopen(lock_fd, "a+b") as lock:
        lock_info = os.fstat(lock.fileno())
        if not stat.S_ISREG(lock_info.st_mode) or lock_info.st_nlink != 1:
            raise ValueError("Refusing unsafe persistence lock")
        deadline = time.monotonic() + 5
        while True:
            check()
            try:
                fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
                break
            except BlockingIOError:
                if time.monotonic() >= deadline:
                    raise TimeoutError("Persistence lock timed out") from None
                time.sleep(0.05)
        check()
        if resolve_target(snapshot.path) != snapshot.resolved_path:
            raise ValueError("Destination changed; review again")
        previous = read_stable(target) if target.exists() else b""
        if previous.decode("utf-8") != snapshot.saved_text:
            raise ValueError("Output file changed; review the updated diff")
        if previous and preservation is None:
            read_document(previous.decode("utf-8"))
            validate_lua(previous.decode("utf-8"))
        backup = None
        if previous == proposed.encode("utf-8"):
            return None
        if preservation is not None:
            check()
            _preserve(preservation, previous)
        elif previous:
            backups = state / "backups"
            # Rollback data must stay outside version-controlled configuration.
            resolved_backups = backups.resolve()
            for parent in (resolved_backups, *resolved_backups.parents):
                if (parent / ".git").exists():
                    raise ValueError("Backup directory must be outside the dotfiles repository")
            backups.mkdir(mode=0o700, exist_ok=True)
            backup = backups / (hashlib.sha256(previous).hexdigest() + ".lua")
            if backup.is_symlink():
                raise ValueError("Refusing symlinked backup")
            if backup.exists():
                if read_stable(backup) != previous:
                    raise ValueError("Refusing foreign or hardlinked backup")
            else:
                try:
                    _atomic_write(backup, previous, exclusive=True)
                except PersistenceFailure as exc:
                    raise PersistenceFailure(str(exc)) from exc
                if read_stable(backup) != previous:
                    raise ValueError("Rollback backup changed during save")
        # Recheck after backup/validation, but do not claim protection from hostile races.
        if (
            resolve_target(snapshot.path) != snapshot.resolved_path
            or (read_stable(target) if target.exists() else b"") != previous
        ):
            raise ValueError("Output file changed during save; review again")
        check()
        if (
            resolve_target(snapshot.path) != target
            or (read_stable(target) if target.exists() else b"") != previous
        ):
            raise ValueError("Output file changed immediately before save; review again")
        if cancel_event is not None and cancel_event.is_set():
            raise InterruptedError("Save cancelled before replacement")
        if preservation is not None:
            _verify_preservation(preservation, previous)

            def before_replace():
                check()
                _verify_preservation(preservation, previous)
                if resolve_target(snapshot.path) != target or read_stable(target) != previous:
                    raise ValueError("Output file changed immediately before recovery")
                if cancel_event is not None and cancel_event.is_set():
                    raise InterruptedError("Recovery cancelled before replacement")

            _atomic_write(target, proposed.encode("utf-8"), before_replace=before_replace)
        else:
            _atomic_write(target, proposed.encode("utf-8"))
        replacing[0] = True
        return backup
