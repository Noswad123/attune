from hyprmod.core import config, health, persistence, restoration


def text(value="5"):
    return persistence.build_text({"general:gaps_in": value}, config.ConfigSections())


@pytest.fixture
def files(tmp_path):
    output = tmp_path / "attune.lua"
    output.write_text(text("9"))
    root = Path(os.environ["XDG_STATE_HOME"]) / "attune/backups"
    root.mkdir(parents=True)
    candidate = root / (hashlib.sha256(text().encode()).hexdigest() + ".lua")
    candidate.write_text(text())
    return output, candidate


def stage(files):
    return restoration.prepare_restore(files[0], files[1].name)


class TestDraft:
    def test_exact_direction_immutable_protocol(self, files):
        draft = stage(files)
        assert draft.diff.startswith("--- current/attune.lua\n+++ " + files[1].name)
        assert "-        gaps_in = 9," in draft.diff
        assert "+        gaps_in = 5," in draft.diff
        assert draft.added_lines == draft.removed_lines == 2
        assert restoration.RestoreDraft.from_json(draft.to_json()) == draft
        with pytest.raises(FrozenInstanceError):
            setattr(draft, "diff", "forged")


class TestCachedRecovery:
    @pytest.mark.parametrize("uncertain", [False, True])
    def test_recovery_retry_reads_restored_disk_instead_of_cached_values(
        self, files, monkeypatch, uncertain
    ):
        with config.managed_path_override(files[0]):
            assert config.read_cached()[0]["general:gaps_in"] == "9"
            draft = stage(files)
            if uncertain:
                persist = persistence.persist_snapshot

                def replaced_then_error(snapshot, **kwargs):
                    persist(snapshot, **kwargs)
                    raise persistence.PersistenceFailure("late error", may_have_written=True)

                monkeypatch.setattr(persistence, "persist_snapshot", replaced_then_error)
                with pytest.raises(restoration.RestoreFailure) as failure:
                    restoration.commit_restore(draft)
                assert failure.value.may_have_written
            else:
                assert restoration.commit_restore(draft).status == "restored"
            assert config.read_cached()[0]["general:gaps_in"] == "5"


class TestDraftRejections:
    @pytest.mark.parametrize("side", [0, 1])
    @pytest.mark.parametrize(
        "bad", ["", "return os.execute('false')\n", "-- Generated by Attune\n", "unknown"]
    )
    def test_noncanonical_refused(self, files, side, bad):
        files[side].write_text(bad)
        with pytest.raises((ValueError, OSError)):
            stage(files)

    @pytest.mark.parametrize("name", ["../a.lua", "/tmp/a.lua", "A" * 64 + ".lua", "x"])
    def test_basename(self, files, name):
        with pytest.raises(ValueError, match="basename"):
            restoration.prepare_restore(files[0], name)

    def test_hash_scope_unknown_version(self, files):
        files[1].write_text(text("7"))
        with pytest.raises(ValueError, match="identity"):
            stage(files)
        record = base64.b64encode(json.dumps([{"exec": "bad"}, {}]).encode()).decode()
        files[0].write_text(persistence.MARKER + persistence.RECORD + record + "\n")
        with pytest.raises(ValueError, match="Unsupported"):
            stage(files)

    @pytest.mark.parametrize(
        "kind", ["missing", "hardlink", "directory", "fifo", "dangling", "cycle", "main"]
    )
    @pytest.mark.parametrize("side", [0, 1])
    def test_unsafe_files(self, files, tmp_path, kind, side):
        path = files[side]
        path.unlink()
        if kind == "hardlink":
            other = tmp_path / "other"
            other.write_text(text())
            os.link(other, path)
        elif kind == "directory":
            path.mkdir()
        elif kind == "fifo":
            os.mkfifo(path)
        elif kind in ("dangling", "cycle"):
            path.symlink_to(path if kind == "cycle" else tmp_path / "missing")
        elif kind == "main":
            path.write_text(text())
            main = Path(os.environ["XDG_CONFIG_HOME"]) / "hypr/hyprland.lua"
            main.parent.mkdir()
            main.symlink_to(path)
            if side == 1:
                path.unlink()
                path.symlink_to(main)
        with pytest.raises((ValueError, OSError)):
            stage(files)

    @pytest.mark.parametrize("failure", ["missing", "syntax", "timeout"])
    def test_validator_fail_closed(self, files, monkeypatch, failure):
        if failure == "missing":
            monkeypatch.setattr(persistence.shutil, "which", lambda _: None)
        else:

            def fail(*args, **kwargs):
                if failure == "timeout":
                    raise subprocess.TimeoutExpired("luac", 10)
                return subprocess.CompletedProcess([], 1, stderr="bad syntax")

            monkeypatch.setattr(persistence.subprocess, "run", fail)
        before = files[0].read_bytes()
        with pytest.raises(ValueError):
            stage(files)
        assert files[0].read_bytes() == before

    @pytest.mark.parametrize(
        "field,value",
        [("diff", ""), ("added_lines", True), ("previous_sha256", "bad"), ("extra", "x")],
    )
    def test_corrupt_protocol(self, files, field, value):
        data = json.loads(stage(files).to_json())
        data[field] = value
        with pytest.raises(ValueError):
            restoration.RestoreDraft.from_json(json.dumps(data))

    def test_protocol_duplicate_deep_oversize(self, files):
        data = stage(files).to_json()
        with pytest.raises(ValueError):
            restoration.RestoreDraft.from_json('{"diff":"",' + data[1:])
        for data in ("[" * 2000, " " * (restoration.MAX_JSON_BYTES + 1)):
            with pytest.raises(ValueError):
                restoration.RestoreDraft.from_json(data)

    def test_limits_no_truncation(self, files, monkeypatch):
        monkeypatch.setattr(restoration, "MAX_DIFF_BYTES", 10)
        with pytest.raises(ValueError, match="Complete"):
            stage(files)
        monkeypatch.setattr(restoration, "MAX_DIFF_BYTES", 256 * 1024)
        monkeypatch.setattr(restoration, "MAX_DIFF_LINES", 1)
        with pytest.raises(ValueError, match="Complete"):
            stage(files)
        files[0].write_bytes(b"x" * (restoration.MAX_INPUT_BYTES + 1))
        with pytest.raises(ValueError, match="limit"):
            stage(files)

    def test_real_supervised_prepare_no_writes(self, files):
        before = {p: p.read_bytes() for p in files}
        draft = restoration.run_prepare(files[0], files[1].name)
        assert draft.previous_text == before[files[0]].decode()
        assert {p: p.read_bytes() for p in files} == before
        assert list(files[1].parent.iterdir()) == [files[1]]

    def test_worker_only_prepare(self, files, monkeypatch):
        seen = []

        def bounded(command, **kwargs):
            seen.extend(command)
            assert kwargs["process_group"] is True
            return subprocess.CompletedProcess(command, 0, stdout=stage(files).to_json())

        monkeypatch.setattr(health, "run_bounded", bounded)
        restoration.run_prepare(files[0], files[1].name)
        assert "prepare" in seen and "commit" not in seen


class TestCommit:
    def test_validator_disappears_after_review(self, files, monkeypatch):
        draft = stage(files)
        monkeypatch.setattr(persistence.shutil, "which", lambda _: None)
        with pytest.raises(restoration.RestoreFailure) as error:
            restoration.commit_restore(draft)
        assert not error.value.may_have_written
        assert files[0].read_text() == draft.previous_text

    def test_restore_reverse_and_source_unchanged(self, files):
        draft = stage(files)
        source = files[1].read_bytes()
        result = restoration.commit_restore(draft)
        assert result.status == "restored"
        assert files[0].read_bytes() == source
        assert result.backup_path is not None
        assert result.backup_path.read_text() == draft.previous_text
        assert result.backup_path != files[1]
        reverse = restoration.prepare_restore(files[0], result.backup_path.name)
        assert restoration.commit_restore(reverse).status == "restored"
        assert files[0].read_text() == draft.previous_text
        assert files[1].read_bytes() == source

    @pytest.mark.parametrize("parent", [False, True])
    def test_stow_preserved(self, files, tmp_path, parent):
        link = tmp_path / ("linked" if parent else "stow")
        if parent:
            link.symlink_to(files[0].parent, target_is_directory=True)
            path = link / "attune.lua"
        else:
            link.mkdir()
            path = link / "attune.lua"
            path.symlink_to(files[0])
        draft = restoration.prepare_restore(path, files[1].name)
        restoration.commit_restore(draft)
        assert (link if parent else path).is_symlink()
        assert files[0].read_bytes() == files[1].read_bytes()

    def test_noop_no_files(self, files):
        files[0].write_bytes(files[1].read_bytes())
        draft = stage(files)
        before = files[0].stat()
        result = restoration.commit_restore(draft)
        assert result.status == "unchanged" and result.backup_path is None
        assert files[0].stat() == before
        assert not (files[1].parent.parent / "persistence.lock").exists()

    @pytest.mark.parametrize("change", ["current", "source", "missing", "root", "target"])
    @pytest.mark.parametrize("when", ["before", "lock", "backup"])
    def test_stale_refused(self, files, tmp_path, monkeypatch, change, when):
        draft = stage(files)

        def mutate():
            if change == "current":
                files[0].write_text(text("7"))
            elif change == "source":
                files[1].write_text(text("7"))
            elif change == "missing":
                files[1].unlink()
            elif change == "root":
                root = files[1].parent
                moved = tmp_path / "moved"
                root.rename(moved)
                root.symlink_to(moved, target_is_directory=True)
            else:
                other = tmp_path / "other/attune.lua"
                other.parent.mkdir()
                other.write_text(draft.previous_text)
                files[0].unlink()
                files[0].symlink_to(other)

        if when == "before":
            mutate()
        elif when == "lock":
            real = persistence.fcntl.flock

            def flock(fd, operation):
                real(fd, operation)
                mutate()

            monkeypatch.setattr(persistence.fcntl, "flock", flock)
        else:
            real_write = persistence._atomic_write

            def write(path, content, **kwargs):
                real_write(path, content, **kwargs)
                if path != files[0]:
                    mutate()

            monkeypatch.setattr(persistence, "_atomic_write", write)
        with pytest.raises(restoration.RestoreFailure) as error:
            restoration.commit_restore(draft)
        assert not error.value.may_have_written
        assert files[0].read_text() != draft.proposed_text

    def test_forged_draft_refused(self, files):
        with pytest.raises(restoration.RestoreFailure):
            restoration.commit_restore(replace(stage(files), proposed_text=text("7")))

    def test_cyclic_backup_root_refused(self, files, tmp_path):
        draft = stage(files)
        root = files[1].parent
        root.rename(tmp_path / "original-backups")
        root.symlink_to(root, target_is_directory=True)
        with pytest.raises(restoration.RestoreFailure) as error:
            restoration.commit_restore(draft)
        assert not error.value.may_have_written
        assert files[0].read_text() == draft.previous_text

    @pytest.mark.parametrize("cancel", [False, True])
    def test_lock_finite_cancel_no_write(self, files, monkeypatch, cancel):
        draft = stage(files)
        event = threading.Event()
        ticks = iter([0, 6])
        monkeypatch.setattr(persistence.time, "monotonic", lambda: next(ticks))

        def busy(*args):
            if cancel:
                event.set()
            raise BlockingIOError()

        monkeypatch.setattr(persistence.fcntl, "flock", busy)
        with pytest.raises(restoration.RestoreFailure) as error:
            restoration.commit_restore(draft, cancel_event=event)
        assert not error.value.may_have_written
        assert files[0].read_text() == draft.previous_text

    def test_cancel_immediately_before_commit(self, files, monkeypatch):
        draft = stage(files)
        event = threading.Event()
        real = persistence._atomic_write

        def backup(path, content, **kwargs):
            real(path, content, **kwargs)
            event.set()

        monkeypatch.setattr(persistence, "_atomic_write", backup)
        with pytest.raises(restoration.RestoreFailure) as error:
            restoration.commit_restore(draft, cancel_event=event)
        assert not error.value.may_have_written
        assert files[0].read_text() == draft.previous_text

    @pytest.mark.parametrize("kind", ["foreign", "symlink", "hardlink", "directory"])
    def test_rollback_collision_refused(self, files, tmp_path, kind):
        draft = stage(files)
        rollback = files[1].parent / (draft.previous_sha256 + ".lua")
        if kind == "foreign":
            rollback.write_text("foreign")
        elif kind == "directory":
            rollback.mkdir()
        else:
            other = tmp_path / "foreign"
            other.write_text(draft.previous_text)
            if kind == "symlink":
                rollback.symlink_to(other)
            else:
                os.link(other, rollback)
        with pytest.raises(restoration.RestoreFailure) as error:
            restoration.commit_restore(draft)
        assert not error.value.may_have_written
        assert files[0].read_text() == draft.previous_text

    @pytest.mark.parametrize("after", [False, True])
    def test_replace_failure_uncertain(self, files, monkeypatch, after):
        draft = stage(files)
        real = os.replace

        def fail(source, target):
            if target == files[0]:
                if after:
                    real(source, target)
                raise OSError("replace failed")
            real(source, target)

        monkeypatch.setattr(persistence.os, "replace", fail)
        with pytest.raises(restoration.RestoreFailure) as error:
            restoration.commit_restore(draft)
        assert error.value.may_have_written
        assert files[0].read_text() == (draft.proposed_text if after else draft.previous_text)

    def test_backup_failure_before_write(self, files, monkeypatch):
        draft = stage(files)

        def fail(*args, **kwargs):
            raise OSError("backup failed")

        monkeypatch.setattr(persistence, "_atomic_write", fail)
        with pytest.raises(restoration.RestoreFailure) as error:
            restoration.commit_restore(draft)
        assert not error.value.may_have_written
        assert files[0].read_text() == draft.previous_text

    def test_backup_collision_during_creation_never_overwritten(self, files, monkeypatch):
        draft = stage(files)
        real = os.link
        collision = []

        def collide(source, target, **kwargs):
            Path(target).write_text("foreign collision")
            collision.append(Path(target))
            real(source, target, **kwargs)

        monkeypatch.setattr(persistence.os, "link", collide)
        with pytest.raises(restoration.RestoreFailure) as error:
            restoration.commit_restore(draft)
        assert not error.value.may_have_written
        assert collision[0].read_text() == "foreign collision"
        assert files[0].read_text() == draft.previous_text

    def test_target_fsync_failure_is_before_replacement(self, files, monkeypatch):
        draft = stage(files)
        (files[1].parent / (draft.previous_sha256 + ".lua")).write_text(draft.previous_text)

        def fail(fd):
            raise OSError("fsync failed")

        monkeypatch.setattr(persistence.os, "fsync", fail)
        with pytest.raises(restoration.RestoreFailure) as error:
            restoration.commit_restore(draft)
        assert not error.value.may_have_written
        assert files[0].read_text() == draft.previous_text

    def test_post_replace_cancel_is_success(self, files, monkeypatch):
        draft = stage(files)
        event = threading.Event()
        real = os.replace

        def replace_and_cancel(source, target):
            real(source, target)
            event.set()

        monkeypatch.setattr(persistence.os, "replace", replace_and_cancel)
        assert restoration.commit_restore(draft, cancel_event=event).status == "restored"
        assert files[0].read_text() == draft.proposed_text

    def test_cleanup_error_after_replace_not_failure(self, files, monkeypatch):
        draft = stage(files)
        (files[1].parent / (draft.previous_sha256 + ".lua")).write_text(draft.previous_text)
        real = Path.unlink

        def unlink(path, **kwargs):
            if path.name.startswith(".attune-") and not path.exists():
                raise OSError("cleanup failed after replace")
            real(path, **kwargs)

        monkeypatch.setattr(Path, "unlink", unlink)
        assert restoration.commit_restore(draft).status == "restored"

    def test_state_inside_git_refused_before_modification(self, files, tmp_path):
        draft = stage(files)
        (tmp_path / ".git").mkdir()
        with pytest.raises(restoration.RestoreFailure) as error:
            restoration.commit_restore(draft)
        assert not error.value.may_have_written
        assert files[0].read_text() == draft.previous_text
        assert not (files[1].parent.parent / "persistence.lock").exists()

    def test_no_ipc_or_executing_reader(self, files, monkeypatch):
        def forbidden(*args, **kwargs):
            raise AssertionError("No IPC or Lua execution")

